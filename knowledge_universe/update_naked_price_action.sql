update public.knowledge_nodes
set
  principle = '「裸K」指的是拿掉所有技術指標，只憑K線本身的實體、影線、排列順序去判讀當下買賣力道——核心假設是「所有資訊最終都會反映在價格上」，指標多半是價格的落後衍生品，裸K想直接讀價格本身。

實體(開盤到收盤的長方形)代表這段時間內贏的一方力道有多強：實體長，代表某一方從頭到尾都壓著另一方打；實體短，代表雙方拉鋸互有攻防。影線(超出實體的細線)代表「曾經到過但守不住」的價位：上影線長，代表買方一度把價格推高、但賣壓在高點把它打回來；下影線長，代表賣方一度砸盤、但買方在低點接住了。

幾種最常被拿來判讀的組合：長下影線(俗稱錘子線/Pin Bar)代表低點有承接力道；長上影線(俗稱流星線)代表高點有壓制力道；吞噬(Engulfing，一根實體完全包住前一根實體)代表力道在這根K線內出現逆轉；內包(Inside Bar，整根K線的高低點都被前一根包住)代表波動收縮、變盤前兆；十字線(開盤收盤幾乎同價)代表多空僵持不下。

但這套判讀最容易被誤用的地方，是把「型態本身」當成訊號，卻不看「型態出現在哪裡」——同一根長下影線，出現在一段跌了很久的趨勢末端，跟出現在盤整區間正中央，代表的意義完全不同(見下方案例)。裸K從來不是拿來單獨使用的完整系統，比較實際的用法是拿它當「確認層」，疊加在結構分析(支撐壓力、趨勢方向、成交量)之上——結構告訴你「在哪裡看」，裸K告訴你「這裡誰在贏」。',
  case_study = '對照著看三個情境，體會「位置」怎麼改變同一種K線型態的意義：

情境一(高品質訊號)：價格連續下跌兩週後，某天出現一根長下影線，收盤價收在當天高點附近，且當天成交量是過去五天平均的兩倍以上——這代表賣方把價格砸到新低點，但買方在那個價位大量進場承接，一天之內就把賣壓吃掉。趨勢末端＋放量＋長下影線，三個條件同時成立，才是相對可信的反轉線索。

情境二(雜訊)：同樣是一根長下影線，出現在一個已經橫盤兩週的盤整區間正中央，成交量跟平常沒有明顯差異——這種情況下比較合理的解讀是「當天盤中正常的來回測試」，不代表任何轉折意義，硬要解讀成買進訊號很容易被隔天的反向走勢打臉。

情境三(結構＋裸K疊加)：價格在前波高點附近整理後拉回，剛好回測到前波高點轉換成的支撐位置，這時候出現一根吞噬型態(當天實體完全包住前一天的下跌實體)——這種「裸K型態出現在關鍵結構位置」的組合，比單獨看裸K或單獨看結構位置，訊號品質都更高，這也是裸K實務上比較站得住腳的用法。',
  common_mistakes = array[
    '把單一根K線的形態(如長下影線)當成必然反轉訊號，忽略所在的整體趨勢背景',
    '在低流動性、低成交量的盤面套用裸K判讀，訊號可靠度大幅下降',
    '只看單一根K線的絕對長短，沒有跟鄰近幾根K線比較相對大小——同樣長度的影線，在低波動盤面可能已經是極端值，在高波動盤面可能只是稀鬆平常',
    '在雜訊多的低週期圖表(如1分鐘線)硬套裸K判讀，同一段走勢換到更高週期(15分/1小時)可能根本看不出這根K線的存在'
  ]
