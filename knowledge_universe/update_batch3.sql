三種方法算出的區間如果高度重疊，代表估值結果較可信，因為三個完全不同角度的方法互相印證同一個答案；如果三個方法算出差異巨大的數字，代表某一個(或多個)方法的假設可能有問題，需要進一步檢視——是DCF的成長率假設太樂觀，還是可比公司裡混進了一家體質完全不同的離群值，或者前例併購交易的年代太久遠、市況跟現在差太多，都要具體去查。

這裡容易被誤解的地方，是把交叉驗證想成「把三個數字加起來除以三」的機械式平均。三隻腳的用意不是算平均數，而是理解「為什麼三者會有落差」，再判斷在這個特定情境下哪一個方法比較站得住腳——有時候正確的做法甚至是直接捨棄其中一個方法的結果，例如產業裡近期完全沒有併購案例可以參考，前例併購交易法的數字就沒有太大意義，硬要拿來平均反而會扭曲最終判斷。

實務上，三隻腳通常是在DCF的假設都已經檢查過一輪之後，用來做最後把關的步驟；估值區間確立之後，下一步該問的是催化劑思維——什麼具體事件會讓市場從現在的價格，往你認為合理的區間移動。',
