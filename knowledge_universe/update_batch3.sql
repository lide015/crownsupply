判斷一個TAM數字可不可信，可以用TAM/SAM/SOM這個漏斗去拆解：TAM是理論上的最大市場(假設拿下100%市占率、甚至把相關的鄰近應用場景都算進去)；SAM(可服務市場)是這家公司的產品、商業模式、地理範圍實際上能觸及的那一塊；SOM(可獲得市場)是在特定時間內、考慮到競爭對手存在的情況下，實際上能拿下的市占率。同時要問這個數字的計算方法跟資料來源是什麼——是由下而上(先算潛在客戶數乘以每個客戶的合理採購金額，再跟同業實際市占率交叉核對)，還是由上而下(直接引用某份產業報告裡一個籠統的總數)。

這裡最容易被誤解的地方，是把「TAM很大」直接等同「這家公司機會很大」。一個龐大的TAM數字，完全沒有回答這家公司實際上能拿到其中多少，也沒有回答「即使這個產業趨勢是真的，價值鏈裡最後是誰真正賺到錢」——很多時候，趨勢本身千真萬確，但因為終端產品規格開放、進入門檻低，真正享有訂價權跟高毛利的，是上游某個關鍵零組件或設備的獨家供應商，而不是市場第一個想到、媒體最常報導的知名品牌廠。「這個市場是真的」跟「這家公司能從中賺到錢」是兩個必須分開回答的問題。

這個檢查應該放在選股篩選的成長型篩選之前或同時進行，因為成長型篩選特別容易被誇大的TAM敘事牽著走；一個被過度誇大的TAM故事，某種程度上也是整個板塊集體情緒過熱的一種具體徵狀，而不只是單一公司的問題。',
