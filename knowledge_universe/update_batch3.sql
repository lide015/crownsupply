  principle = '核心邏輯是「一家公司值多少錢，等於它未來能產生的自由現金流，折算回現在的價值」。這個概念背後的道理很單純：今天拿到一塊錢，跟十年後才拿到一塊錢，價值並不一樣，因為錢有時間價值，也因為越遠的未來越不確定。DCF存在的意義，是強迫分析者把「這家公司到底值多少錢」這個模糊的問題，拆解成一連串明確、可以被檢驗、可以被挑戰的假設，而不是單純參考市場現在的價格。

具體做法是先估算未來幾年的自由現金流(稅後營業利益加回折舊攤銷、扣掉資本支出與營運資金增加)，再用反映資金成本與風險的折現率(加權平均資金成本，WACC，由股東要求的報酬率與稅後負債成本依資本結構比重加權而成)折現回現在，加總得出企業價值。折現率越高，代表要求的風險溢酬越高，算出來的合理價就越低；同樣一組現金流假設，換一個折現率，答案可以差距很大。

這裡最容易誤解的地方，是把DCF算出來的數字當成「這家公司客觀上就值這個價格」的精確答案。實際上DCF不是一台能預測未來的機器，它只是把你對這家公司的假設，用數學方式忠實地換算成一個價格——假設是保守的，答案就保守；假設是樂觀的，答案就樂觀。DCF算出的是「價值」，不是「市場什麼時候會認同這個價值」，這兩者可以長期脫節，看到一個漂亮的DCF數字，該問的第一個問題永遠是「這些假設合理嗎」，而不是照單全收。

在整個研究流程裡，DCF通常不是單獨使用的工具，比較站得住腳的用法，是把它當成估值三隻腳裡最能反映內在價值的一隻腳，搭配可比公司倍數與前例併購交易互相檢驗；同時DCF對企業的適用程度也不一樣，現金流可預測性高的成熟公司(例如穩定的公用事業或民生消費品)用DCF比較可靠，早期高成長、近幾年現金流還是負的公司，DCF的答案幾乎全靠終值裡對遙遠未來的假設撐著，可信度天生就比較低。',
