最常見的算法是永續成長模型：終值等於預測期最後一年的自由現金流乘以(1+永續成長率)，再除以(WACC減永續成長率)。這個公式有個數學上的脆弱點：分母是WACC減永續成長率，當永續成長率被設定得越接近WACC，分母越趨近於零，算出來的終值會被不成比例地放大，一點點成長率假設的調整，就能讓終值暴增。因為終值來自「無限期」的現金流，即使折現率把它壓縮回現在，占總估值的比重往往還是達到六到七成以上，尤其是近期現金流還小的成長型公司，這個比例可能超過九成。

